package main

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

const shapeSrc = `package p

//sumtype:decl
type Shape interface {
	isShape()
}

//gosumtype:impl Shape
type (
	Circle struct {
		Radius float64
	}
	Square struct {
		Side float64
	}
	Triangle struct {
		Base   float64
		Height float64
	}
	Rectangle struct {
		Width  float64
		Height float64
	}
)
`

const shapeWithGenericsSrc = `package p

//sumtype:decl
type Shape interface {
	isShape()
}

//gosumtype:impl Shape
type (
	Circle struct {
		Radius float64
	}
	Square struct {
		Side float64
	}
	Triangle struct {
		Base   float64
		Height float64
	}
	Scaled[N interface{ ~float64 }] struct {
		Inner  Shape
		Factor N
	}
)
`

func TestIntegration_processWritesOutputFile(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	inputFile := filepath.Join(dir, "shapes.go")
	if err := os.WriteFile(inputFile, []byte(shapeSrc), 0644); err != nil {
		t.Fatalf("write input: %v", err)
	}

	if err := process(inputFile); err != nil {
		t.Fatalf("process: %v", err)
	}

	outputFile := filepath.Join(dir, "shapes_sumtypes.go")
	data, err := os.ReadFile(outputFile)
	if err != nil {
		t.Fatalf("read output file: %v", err)
	}

	src := string(data)
	if !strings.HasPrefix(src, "// Code generated by go-sumtype. DO NOT EDIT.") {
		t.Error("output missing do-not-edit header")
	}
	if !strings.Contains(src, "package p") {
		t.Error("output missing package declaration")
	}
	// go/format aligns {} bodies for same-named functions; check signature only.
	for _, want := range []string{
		"func (*Circle) isShape()",
		"func (*Square) isShape()",
		"func (*Triangle) isShape()",
		"func (*Rectangle) isShape()",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("output missing %q\n\nfull output:\n%s", want, src)
		}
	}
}

func TestIntegration_noSumTypeBlocksWritesNoOutputFile(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	inputFile := filepath.Join(dir, "types.go")
	if err := os.WriteFile(inputFile, []byte(`package p

type (
	Shape  interface{ String() string }
	Circle struct{}
)
`), 0644); err != nil {
		t.Fatalf("write input: %v", err)
	}

	if err := process(inputFile); err != nil {
		t.Fatalf("process: %v", err)
	}

	outputFile := filepath.Join(dir, "types_sumtypes.go")
	if _, err := os.Stat(outputFile); !os.IsNotExist(err) {
		t.Error("expected no output file when no sumtype blocks present")
	}
}

